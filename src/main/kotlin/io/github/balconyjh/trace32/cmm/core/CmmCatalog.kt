        private val BY_NAME: Map<String, Entry> = buildMap {
            for (entry in ENTRIES) {
                putIfAbsent(entry.name.uppercase(Locale.ROOT), entry)
                for (alias in entry.aliases) putIfAbsent(alias.uppercase(Locale.ROOT), entry)
            }
        }
        @JvmStatic fun entries(): List<Entry> = ENTRIES
        @JvmStatic fun find(name: String): Entry? = BY_NAME[name.removeSuffix("()").uppercase(Locale.ROOT)]
        @JvmStatic fun canonicalName(name: String): String = find(name)?.name ?: name
        @JvmStatic fun isKeyword(word: String): Boolean = canonicalName(word).uppercase(Locale.ROOT) in KEYWORDS
